"""Phase 3 board step F (v5): export the C-part parameters and the VAL cells (never test) for the on-board streaming app.
Writes fw/naion_params.h (gate MLP, extrapolation constants, label scaler) and fw/naion_data.c (per val cell: cycle
curves [nmax][3][300] float32 placed in external flash, true EOL, host reference EOL per prefix from the ST INT8 chain).
Usage: BL_SPLIT=2021 python phase3/board/fw/gen_fw_data.py"""
import json, os, sys
from pathlib import Path
import numpy as np, torch, onnxruntime as ort
B = Path(__file__).resolve().parents[1]; ROOT = B.parents[1]; sys.path.insert(0, str(B))
from st_split_export import c_part, RUNS
from st_int8 import states_for

def arr(name, a, ctype="float", sect=""):
    a = np.asarray(a).ravel()
    fl = lambda v: (lambda t: t if ("." in t or "e" in t or "n" in t) else t + ".0")(f"{float(v):.9g}") + "f"
    body = ",".join(fl(v) if ctype == "float" else str(int(v)) for v in a)
    return f"{sect}const {ctype} {name}[{a.size}] = {{{body}}};\n"

if __name__ == "__main__":
    split = os.environ.get("BL_SPLIT", "2021"); eid = RUNS[split]; out = B / "fw"
    G = json.loads((B / f"{eid}_C_params.json").read_text())
    d = torch.load(ROOT / f".cache/batterylife_naion_split{split}_v1.pt", weights_only=False); sc = d["label_scaler"]
    sE = ort.InferenceSession(str(B / f"{eid}_E_int8.onnx"), providers=["CPUExecutionProvider"])
    sH = ort.InferenceSession(str(B / f"{eid}_H_int8.onnx"), providers=["CPUExecutionProvider"])
    W1 = np.array(G["W1"]); hd = W1.shape[0]
    h = [f"/* generated by gen_fw_data.py for {eid} (split {split}); C part of NaFadeNet+ExtrapGate */",
         "#pragma once", "#if defined(__arm__)", '#define NA_EXT_SECTION /* const data -> .rodata -> XSPI2 (linker FLASH=0x70000000) */', "#else", "#define NA_EXT_SECTION", "#endif", f'#define NA_TAG "{eid} split{split}"', f"#define NA_WINDOW {int(G['window'])}", f"#define NA_THR {G['thr']!r}", f"#define NA_CAP {G['cap']!r}",
         f"#define NA_S {G['s']!r}", f"#define NA_DA {G['da']!r}", f"#define NA_DC {G['dc']!r}",
         f"#define NA_FADE_SCALE {G['fade_scale']!r}", f"#define NA_B2 {G['b2']!r}", f"#define NA_HID {hd}",
         f"#define NA_LABEL_SCALE {float(sc['scale'])!r}", f"#define NA_LABEL_MEAN {float(sc['mean'])!r}",
         "extern const float na_W1[NA_HID*4]; extern const float na_b1[NA_HID]; extern const float na_W2[NA_HID];",
         "typedef struct { int nmax; float eol; const float *curves; const float *ref_eol; } na_cell_t;",
         "extern const na_cell_t na_cells[]; extern const int na_ncells;", ""]
    (out / "naion_params.h").write_text("\n".join(h))
    EXT = "NA_EXT_SECTION "
    src = ['#include "naion_params.h"', arr("na_W1", W1), arr("na_b1", G["b1"]), arr("na_W2", G["W2"])]
    cells, ape = [], []
    for k, c in enumerate(d["cells"]["val"]):
        X = c["tensor"].numpy().astype(np.float32); nmax = min(100, int(np.ceil(c["eol"])) - 1)
        hh = np.stack([sE.run(None, {"curve": X[i:i + 1]})[0][0] for i in range(nmax)])
        qd, qc = X[:, 2, 150:].max(1), X[:, 2, :150].max(1); ref = []
        for n in range(1, nmax + 1):
            st, mk = states_for(hh, qd, qc, n, G["fade_scale"])
            y = c_part(qd, n, float(sH.run(None, {"states": st[None], "mask": mk[None]})[0][0, 0]), G)
            ref.append(y * sc["scale"] + sc["mean"]); ape.append(abs(ref[-1] - c["eol"]) / c["eol"])
        src.append(arr(f"na_curves_{k}", X[:nmax], sect=EXT)); src.append(arr(f"na_ref_{k}", ref))
        cells.append(f"{{{nmax}, {float(c['eol']):.6f}f, na_curves_{k}, na_ref_{k}}}")
    src.append("const na_cell_t na_cells[] = {" + ", ".join(cells) + "};")
    src.append(f"const int na_ncells = {len(cells)};\n")
    (out / "naion_data.c").write_text("\n".join(src))
    print(f"{eid}: {len(cells)} val cells, {len(ape)} prefixes, host INT8 reference val MAPE {np.mean(ape):.6f}; "
          f"naion_data.c {(out / 'naion_data.c').stat().st_size / 1e6:.1f} MB")
